#!/usr/bin/env bash
# Hyprdots kept its Waybar modules as bare fragments ('"cpu": { ... },') for
# its config generator to paste together. HyDE includes every "*json*" file in
# ~/.config/waybar/modules/ as a document of its own and never touches that
# directory, so after an install on top of Hyprdots Waybar reads a fragment as
# the string "cpu" and aborts with "Json::Value::resolveReference(key, end):
# requires objectValue" (#1992).
#
# The migration moves aside every module Waybar cannot load, and only those:
# a module that loads today must survive untouched.

. "$(dirname -- "$0")/lib/common.sh"

migration="$REPO_ROOT/Scripts/migrations/v26.10.1.sh"

if [ ! -f "$migration" ]; then
    fail "no migration retires the Hyprdots Waybar modules"
    finish
fi

work_dir=$(mktemp -d)
trap 'rm -rf "$work_dir"' EXIT

home_dir="$work_dir/home"
config_home="$work_dir/config"
state_home="$work_dir/state"
modules="$config_home/waybar/modules"
backup="$state_home/hyde/migration/v26.10.1/waybar/modules"

# Waybar cannot load any of these.
broken="cpu.jsonc header.jsonc footer.jsonc empty.jsonc comments.jsonc number.json"
# Waybar loads all of these.
loadable="placeholder.jsonc mine.jsonc exec.jsonc bom.jsonc array.json trailing.jsonc"

seed() {
    rm -rf "$home_dir" "$config_home" "$state_home"
    mkdir -p "$home_dir" "$modules" "$state_home"

    # Hyprdots' own files, abridged: a fragment, the header that opens the
    # object with unquoted placeholders, and the footer that closes it.
    cat >"$modules/cpu.jsonc" <<'EOF'
    "cpu": {
        "interval": 10,
        "format": "󰍛 {usage}%",
        "rotate": ${r_deg},
        "format-alt": "{icon0}{icon1}{icon2}{icon3}"
    },
EOF
    cat >"$modules/header.jsonc" <<'EOF'
//   --// waybar config generated by wbarconfgen.sh //--   //

{
// sourced from header module //

    "layer": "top",
    "output": [ ${w_output} ],
    "position": "${w_position}",
    "${hv_pos}": ${w_height},
EOF
    cat >"$modules/footer.jsonc" <<'EOF'

    "custom/r_end": {
        "format": " ",
        "interval" : "once",
        "tooltip": false
    }
}
EOF
    : >"$modules/empty.jsonc"
    printf '/* nothing yet */\n// still nothing\n' >"$modules/comments.jsonc"
    printf '42\n' >"$modules/number.json"

    # HyDE's own placeholder, a user's module, '${...}' inside strings and
    # comments, a byte order mark, an array and a trailing comma.
    cat >"$modules/placeholder.jsonc" <<'EOF'
/*
To use updated module, please delete this file.
*/
{}
EOF
    cat >"$modules/mine.jsonc" <<'EOF'
// my clock
{
    "clock": { "format": "{:%H:%M}" }
}
EOF
    cat >"$modules/exec.jsonc" <<'EOF'
/* runs ${HOME}/bin/x */
{ "custom/x": { "exec": "${HOME}/bin/x \"${1}\" \\", "format": "//" } } // ${done}
EOF
    printf '\357\273\277{ "tray": {} }\n' >"$modules/bom.jsonc"
    printf '[ { "battery": {} } ]\n' >"$modules/array.json"
    printf '{ "memory": { "interval": 30, }, }\n' >"$modules/trailing.jsonc"

    # Outside the "*json*" include glob.
    printf '"stale"\n' >"$modules/notes.txt"
}

run_migration() {
    (
        HOME="$home_dir" XDG_CONFIG_HOME="$config_home" XDG_STATE_HOME="$state_home" \
            sh "$migration" </dev/null
    ) >"$work_dir/out.log" 2>&1
}

seed
run_migration
status=$?

[ "$status" -eq 0 ] || fail "the migration failed on a machine it should act on: $(cat "$work_dir/out.log")"

for name in $broken; do
    [ -e "$modules/$name" ] && fail "$name cannot be loaded by Waybar, but was left in place"
    [ -f "$backup/$name" ] || fail "$name was not kept in the backup"
done
cmp -s "$backup/cpu.jsonc" - <<'EOF' || fail "the backup of cpu.jsonc is not the original file"
    "cpu": {
        "interval": 10,
        "format": "󰍛 {usage}%",
        "rotate": ${r_deg},
        "format-alt": "{icon0}{icon1}{icon2}{icon3}"
    },
EOF

for name in $loadable; do
    [ -f "$modules/$name" ] || fail "$name loads in Waybar, but was moved"
    [ -e "$backup/$name" ] && fail "$name loads in Waybar, but was backed up"
done
[ -f "$modules/notes.txt" ] || fail "a file outside the include glob was moved"

grep -q "$backup" "$work_dir/out.log" || fail "the migration does not say where the files went"

# Nothing to do on a second pass.
run_migration
[ "$?" -eq 0 ] || fail "a second run failed: $(cat "$work_dir/out.log")"

# The same leftover comes back: its copy is already kept, so it goes, and the
# migration does not fail on every restore from then on.
cp "$backup/cpu.jsonc" "$modules/cpu.jsonc"
run_migration
[ "$?" -eq 0 ] || fail "a leftover identical to its backup failed the run: $(cat "$work_dir/out.log")"
[ -e "$modules/cpu.jsonc" ] && fail "a leftover identical to its backup was left in place"
[ -f "$backup/cpu.jsonc" ] || fail "the backup was lost while removing an identical leftover"

# A different file under the same name must not overwrite the kept copy.
printf '"cpu": {},\n' >"$modules/cpu.jsonc"
run_migration
[ "$?" -ne 0 ] || fail "the run succeeded although a different file could not be backed up"
[ -f "$modules/cpu.jsonc" ] || fail "a file that could not be backed up was moved anyway"
cmp -s "$backup/cpu.jsonc" - <<'EOF' || fail "a rerun overwrote the backup"
    "cpu": {
        "interval": 10,
        "format": "󰍛 {usage}%",
        "rotate": ${r_deg},
        "format-alt": "{icon0}{icon1}{icon2}{icon3}"
    },
EOF

# A machine without Waybar modules: nothing to do.
rm -rf "$config_home/waybar"
run_migration
[ "$?" -eq 0 ] || fail "the migration failed on a machine with no Waybar modules"
[ -e "$config_home/waybar" ] && fail "the migration created a Waybar directory"

finish
